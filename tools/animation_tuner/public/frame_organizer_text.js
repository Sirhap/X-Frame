  /**
   * Creates a translator bound to the current organizer language.
   * @param {()=>string} getLanguage Returns the active language code.
   * @returns {(key:string,variables?:Record<string,string|number>)=>string}
   */
  function createTranslator(getLanguage) {
    return (key, variables = {}) => {
      const language = getLanguage() === "en" ? "en" : "zh";
      const template = TEXT[language]?.[key] || TEXT.zh[key] || key;
      return String(template).replace(/\{(\w+)\}/g, (_match, name) => variables[name] ?? "");
    };
  }

  return { TEXT, createTranslator };
